export function translate(language: Language, source: string, vars?: Record<string, string | number>) {
  let value = language === 'en' ? (EN[source] ?? source) : source
  if (vars) {
    Object.entries(vars).forEach(([key, replacement]) => {
      value = value.split(`{${key}}`).join(String(replacement))
    })
  }
  return value
}
